/**
 * 版本更新公告 —— 弹窗内容唯一的真源。
 *
 * 规则：
 * - **改 `version` 才会重新弹**。用户关掉弹窗后，这个版本号会记进 localStorage；
 *   只改 `items` 而不改 `version`，老用户永远看不到新内容。
 * - 版本号用**发布日期**，形如 `2026.10.23`；一天发两次就写 `2026.10.23-2`。
 *   不维护递增规则，发版当天改成当天日期即可。
 * - 每个版本只弹一次，不是每次进入都弹。
 * - `items` 写**用户能感知的变化**（新功能、行为变化、修复了他们报的问题），
 *   内部重构、依赖升级不用列。
 */
export interface UpdateNotice {
  /** 版本号（发布日期），发布新版本时改这里 */
  version: string;
  /** 发布日期，YYYY-MM-DD，仅用于展示 */
  date: string;
  /** 更新内容，一条一行 */
  items: string[];
}

